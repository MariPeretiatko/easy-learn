import { readFileSync, writeFileSync } from "node:fs";
const bundle = JSON.parse(
  readFileSync("src/data/deutsch-organized.json", "utf8"),
);
const rows = new Map();
const quote = (s) => `'${s.replaceAll("'", "''")}'`;
for (const folder of bundle.folders)
  for (const module of folder.modules)
    for (const deck of module.decks) {
      rows.set(`decks:${deck.id}`, ["decks", deck.id]);
      for (const card of deck.cards) {
        const norm = (s) =>
          s.normalize("NFC").trim().toLocaleLowerCase().replace(/\s+/g, " ");
        const identity = JSON.stringify([
          bundle.language,
          bundle.nativeLanguage,
          norm(card.term),
          norm(card.translation),
        ]);
        let h1 = 2166136261,
          h2 = 5381;
        for (const char of identity) {
          h1 = Math.imul(h1 ^ char.charCodeAt(0), 16777619);
          h2 = Math.imul(h2, 33) ^ char.charCodeAt(0);
        }
        const id = `catalog-${(h1 >>> 0).toString(16).padStart(8, "0")}${(h2 >>> 0).toString(16).padStart(8, "0")}`;
        rows.set(`words:${id}`, ["words", id]);
      }
    }
writeFileSync(
  "supabase/seed.sql",
  `-- Generated by node scripts/catalog-seed.mjs; contains only public identifiers.\ninsert into public.catalog_keys(kind,id) values\n${[...rows.values()].map((row) => `(${row.map(quote).join(",")})`).join(",\n")}\non conflict do nothing;\n`,
);
console.log(`Prepared ${rows.size} public catalog references.`);
